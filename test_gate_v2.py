"""Self-contained tests for contributing.py v2 (2026-11-26).

Run from this directory: python3 test_gate_v2.py
No network, no hands checkout: the openhuman corpus ships in corpus/openhuman/.
"""
import importlib.util, os

HERE = os.path.dirname(os.path.abspath(__file__))

def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m

v2 = load("v2", os.path.join(HERE, "contributing.py"))

def assess(files):
    return v2.assess(files)

# --- the two real-world false positives, fixed by v2 ---

oh = {}
for p in ("CONTRIBUTING.md", "CODE_OF_CONDUCT.md"):
    with open(os.path.join(HERE, "corpus", "openhuman", p)) as f:
        oh[p] = f.read()
r = assess(oh)
print("openhuman:", r["verdict"], "| evidence reads:", [e["reads"] for e in r["evidence"]])
assert r["verdict"] == "allows", "v2 must clear the openhuman false positive"
assert all(e["reads"] in ("requires", "pointer") for e in r["evidence"]), r["evidence"]

r = assess({"CONTRIBUTING.md": "We maintain this repository with the help of AI agents."})
print("self-process:", r["verdict"], "| evidence reads:", [e["reads"] for e in r["evidence"]])
assert r["verdict"] == "allows"
print("self-process: PASS")

# --- real bans must still forbid ---

bans = {
    "AI_POLICY.md": "Contributions generated by AI tools are not accepted in this repository. Pull requests authored by bots will be closed without review.",
    "CONTRIBUTING.md": "We do not work with AI-generated code. Submissions made by LLMs are prohibited and will be rejected. Human contributors only.",
    ".github/CONTRIBUTING.md": "Do not submit machine-generated content. Any automated contributions are banned.",
    "CODE_OF_CONDUCT.md": "No AI-generated contributions. Bots are not permitted.",
    "docs/CONTRIBUTING.md": "AI-written pull requests are unacceptable here. We ban such submissions and they will not be accepted.",
}
for path, text in bans.items():
    r = assess({path: text})
    print(f"synthetic ban [{path}]:", r["verdict"])
    assert r["verdict"] == "forbids", f"regression: real ban {path} no longer forbids"

# --- requirement wording only counts without a prohibition keyword ---

r = assess({"CONTRIBUTING.md": "AI-authored PRs must include metadata, but AI contributions are banned."})
assert r["verdict"] == "forbids", r
print("requirement+ban still forbids: PASS")

# --- pointer into a forbidding target forbids; pointer to an unread file stays neutral ---

r = assess({"CONTRIBUTING.md": "For AI rules, see AI_POLICY.md.", "AI_POLICY.md": "AI contributions are banned here."})
assert r["verdict"] == "forbids", r
print("pointer into forbidding target: PASS")

r = assess({"CONTRIBUTING.md": "For AI rules, see AGENTS.md."})
# sentence-level neutral (reads "pointer"); with no other evidence the repo
# grades allows - the residual blind spot accepted and noted in the docstring
assert r["verdict"] == "allows" and r["evidence"][0]["reads"] == "pointer", r
print("pointer to unread file stays neutral: PASS")

# --- a code block naming an 'agent' directory is not a policy sentence ---

r = assess({"CONTRIBUTING.md": "Repo layout:\n```\nagent/\napps/\n```\nBe kind."})
assert r["verdict"] == "silent", r
print("code-block tree silent: PASS")

# --- hands case compatibility (the exact strings from hands/tests/gh/test_reads.py) ---

cases = [
    ("We do not accept AI-generated pull requests.", "forbids"),
    ("Contributions written by LLMs will be closed without review.", "forbids"),
    ("No ChatGPT or Copilot output, please.", "forbids"),
    ("Bots are banned from opening issues.", "forbids"),
    ("Pull requests created by autonomous agents are prohibited.", "forbids"),
    ("AI-assisted contributions are welcome, as long as you disclose them.", "allows"),
    ("Run the tests before you open a pull request. Be kind.", "silent"),
    ("Please read our AI policy before contributing.", "forbids"),
    ("AI tools are welcome for research.\n\nAI-generated code is not accepted.", "forbids"),
]
ok = True
for text, want in cases:
    got = assess({"CONTRIBUTING.md": text})["verdict"]
    flag = "OK " if got == want else "FAIL"
    if flag == "FAIL":
        ok = False
    print(f"{flag} want={want:8s} got={got:8s} | {text[:60]}")
assert ok, "hands case compatibility FAILED"
print("HANDS CASE COMPATIBILITY: PASS")
print("ALL v2 TESTS PASS")
